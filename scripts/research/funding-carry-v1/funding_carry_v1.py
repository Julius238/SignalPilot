@dataclass
class Market:
    symbol: str
    start: int
    end: int
    spot: dict[int, Bar]
    perp: dict[int, Bar]
    mark: dict[int, Bar]
    funding: list[tuple[int, float]]  # (slot, rate), sorted


@dataclass(frozen=True)
class RunConfig:
    variant: str  # "A" = CARRY_ALWAYS, "B" = CARRY_FUNDING_7D_POSITIVE
    cost_multiplier: float = 1.0
    perp_cost: LegCost = PERP_TAKER_COST
    legging: bool = False


VARIANT_KEYS = {"A": "CARRY_ALWAYS", "B": "CARRY_FUNDING_7D_POSITIVE"}


class _Book:
    """Cash in the spot wallet, collateral in the futures wallet; transfers are free and instant."""

    def __init__(self, capital: float, spot_rate: float, perp_rate: float):
        self.cash = capital
        self.collateral = 0.0
        self.spot_qty = 0.0
        self.short_qty = 0.0
        self.avg_entry = 0.0
        self.spot_rate = spot_rate
        self.perp_rate = perp_rate

    def equity(self, spot_price: float, mark_price: float) -> float:
        return self.cash + self.collateral + self.spot_qty * spot_price + self.short_qty * (self.avg_entry - mark_price)

    def hedged(self) -> bool:
        return self.spot_qty > 0 and self.short_qty > 0

    def flat(self) -> bool:
        return self.spot_qty == 0 and self.short_qty == 0

    def rebuild(self, spot_open: float, perp_open: float, mark_open: float) -> tuple[float, float]:
        """Both legs to N = E / 2 in the same coin quantity (§3.1)."""
        equity = self.equity(spot_open, mark_open)
        if equity <= 0:
            raise StudyError("Sleeve equity is not positive; the hedge cannot be rebuilt.")
        target = equity / 2 / spot_open
        spot_delta = target - self.spot_qty
        spot_cost = abs(spot_delta) * spot_open * self.spot_rate
        self.cash -= spot_delta * spot_open + spot_cost
        self.spot_qty = target
        perp_delta = target - self.short_qty
        perp_cost = abs(perp_delta) * perp_open * self.perp_rate
        if perp_delta < 0:
            self.collateral += -perp_delta * (self.avg_entry - perp_open)
        elif perp_delta > 0:
            self.avg_entry = (self.short_qty * self.avg_entry + perp_delta * perp_open) / target
        self.short_qty = target
        self.collateral += self.cash - perp_cost
        self.cash = 0.0
        return spot_cost + perp_cost, max(abs(spot_delta), abs(perp_delta))

    def close(self, spot_price: float, perp_price: float) -> tuple[float, float]:
        moved = max(self.spot_qty, self.short_qty)
        spot_cost = self.spot_qty * spot_price * self.spot_rate
        perp_cost = self.short_qty * perp_price * self.perp_rate
        self.cash += self.spot_qty * spot_price - spot_cost
        self.collateral += self.short_qty * (self.avg_entry - perp_price) - perp_cost
        self.cash += self.collateral
        self.collateral = self.spot_qty = self.short_qty = self.avg_entry = 0.0
        return spot_cost + perp_cost, moved

    def liquidate(self) -> None:
        """The whole collateral is lost; the spot leg stays (§3.1)."""
        self.collateral = self.short_qty = self.avg_entry = 0.0

    def charge(self, amount: float) -> None:
        if self.short_qty > 0 or self.collateral != 0:
            self.collateral -= amount
        else:
            self.cash -= amount


@dataclass
class SleeveResult:
    symbol: str
    config: RunConfig
    start: int
    start_equity: float
    final_equity: float
    hourly: list[tuple[int, float]]
    daily: list[tuple[str, float]]
    funding_by_day: dict[str, float]
    costs_by_day: dict[str, float]
    legging_by_day: dict[str, float]
    entries: int = 0
    exits: int = 0
    rehedges: int = 0
    rebalances: int = 0
    liquidations: list[str] = field(default_factory=list)
    hours_in_market: int = 0
    hours_total: int = 0
    max_leverage: float = 0.0
    min_liquidation_distance: float | None = None
    min_eu_close_out_distance: float | None = None
    max_legging_loss: float = 0.0


def _last_bar_before(bars: dict[int, Bar], hour: int, lookback_hours: int = 48) -> Bar | None:
    for step in range(lookback_hours + 1):
        bar = bars.get(hour - step * HOUR)
        if bar is not None:
            return bar
    return None


def simulate(market: Market, config: RunConfig, capital: float = SLEEVE_CAPITAL) -> SleeveResult:
    slots = [slot for slot, _ in market.funding]
    prefix = [0.0]
    for _, rate in market.funding:
        prefix.append(prefix[-1] + rate)
    funding_at = dict(market.funding)

    def trailing_sum(decision: int) -> float:
        """S₇: settlements with slot in [d − 7 days, d); the slot at d is not yet known (§2.3)."""
        low = bisect.bisect_left(slots, decision - FILTER_DAYS * DAY)
        high = bisect.bisect_left(slots, decision)
        return prefix[high] - prefix[low]

    book = _Book(capital, SPOT_COST.per_side(config.cost_multiplier), config.perp_cost.per_side(config.cost_multiplier))
    result = SleeveResult(market.symbol, config, market.start, capital, capital, [], [], {}, {}, {})
    first = {name: _last_bar_before(bars, market.start) for name, bars in (("spot", market.spot), ("perp", market.perp), ("mark", market.mark))}
    if any(bar is None for bar in first.values()):
        raise StudyError(f"{market.symbol}: no prices at the sleeve start {iso(market.start)}.")
    last_spot, last_perp, last_mark = first["spot"][0], first["perp"][0], first["mark"][0]
    pending: str | None = None
    reference: float | None = None
    hour = market.start
    while hour < market.end:
        day = day_key(hour)
        s, p, m = market.spot.get(hour), market.perp.get(hour), market.mark.get(hour)
        # 1. Settlement of this slot for the position held into the hour (entry < t <= exit).
        rate = funding_at.get(hour)
        if rate is not None and book.short_qty > 0:
            amount = rate * book.short_qty * (m[0] if m else last_mark)
            book.collateral += amount
            result.funding_by_day[day] = result.funding_by_day.get(day, 0.0) + amount
        # 2. Daily decision at 00:00 UTC.
        if hour % DAY == 0:
            want = True if config.variant == "A" else trailing_sum(hour) > FILTER_THRESHOLD
            if want:
                if not book.hedged():
                    pending = "build"
            else:
                pending = "exit" if not book.flat() else None
        # 3. Execution at the open, both legs together, only with all bars present (D4).
        if pending is not None and s and p and m:
            if pending == "exit":
                cost, moved = book.close(s[0], p[0])
                result.exits += 1
            else:
                kind = "entry" if book.flat() else ("rehedge" if pending == "build" else "rebalance")
                cost, moved = book.rebuild(s[0], p[0], m[0])
                reference = m[0]
                if kind == "entry":
                    result.entries += 1
                elif kind == "rehedge":
                    result.rehedges += 1
                else:
                    result.rebalances += 1
            result.costs_by_day[day] = result.costs_by_day.get(day, 0.0) + cost
            if config.legging:
                # L1: the second leg one hour later, in the less favourable order (M17).
                following = market.spot.get(hour + HOUR)
                loss = moved * abs((following[0] if following else s[3]) - s[0])
                book.charge(loss)
                result.legging_by_day[day] = result.legging_by_day.get(day, 0.0) + loss
                result.max_legging_loss = max(result.max_legging_loss, loss)
            pending = None
        # 4. Liquidation on the hour's mark high.
        if m and book.short_qty > 0:
            high = m[1]
            collateral_equity = book.collateral + book.short_qty * (book.avg_entry - high)
            notional = book.short_qty * high
            if collateral_equity <= MAINTENANCE_MARGIN * notional:
                book.liquidate()
                result.liquidations.append(iso(hour))
                pending = None  # unhedged until the next decision
            else:
                result.max_leverage = max(result.max_leverage, notional / collateral_equity)
                base = book.collateral + book.short_qty * book.avg_entry
                liquidation = base / (book.short_qty * (1 + MAINTENANCE_MARGIN)) / high - 1
                close_out = base / (book.short_qty * (1 + EU_CLOSE_OUT_RATIO)) / high - 1
                result.min_liquidation_distance = liquidation if result.min_liquidation_distance is None else min(result.min_liquidation_distance, liquidation)
                result.min_eu_close_out_distance = close_out if result.min_eu_close_out_distance is None else min(result.min_eu_close_out_distance, close_out)
        # 5. Rebalancing trigger at the close.
        if m and book.hedged() and reference is not None and pending is None:
            if m[3] >= reference * (1 + REBALANCE_BAND) or m[3] <= reference * (1 - REBALANCE_BAND):
                pending = "rebalance"
        # 6. Marks.
        if s:
            last_spot = s[3]
        if p:
            last_perp = p[3]
        if m:
            last_mark = m[3]
        equity = book.equity(last_spot, last_mark)
        result.hourly.append((hour, equity))
        result.hours_total += 1
        if book.hedged():
            result.hours_in_market += 1
        if (hour + HOUR) % DAY == 0:
            result.daily.append((day, equity))
        hour += HOUR
    # End: liquidation value with exit costs of both legs (§3.1).
    cost, _ = book.close(last_spot, last_perp)
    last_day = day_key(market.end - HOUR)
    result.costs_by_day[last_day] = result.costs_by_day.get(last_day, 0.0) + cost
    result.final_equity = book.cash
    if result.daily:
        result.daily[-1] = (result.daily[-1][0], book.cash)
    if result.hourly:
        result.hourly[-1] = (result.hourly[-1][0], book.cash)
    return result


def market_for(data: SymbolData, start: int | None = None, end: int = WINDOW_END) -> Market:
    begin = data.start if start is None else start
    funding = [(event.slot, event.rate) for event in data.funding if event.slot < end]
    return Market(data.symbol, begin, end, data.spot, data.perp, data.mark, funding)


