KLINE_HEADER = "open_time,open,high,low,close,volume,close_time,quote_volume,count,taker_buy_volume,taker_buy_quote_volume,ignore"
SYNTHETIC_FUNDING_MEAN = {2019: 0.0001, 2020: 0.0001, 2021: 0.00025, 2022: -0.00002, 2023: 0.0001, 2024: 0.00015, 2025: 0.00008, 2026: 0.00006}


def _write_zip(path: Path, csv_name: str, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as archive:
        info = zipfile.ZipInfo(csv_name, date_time=(2026, 10, 1, 0, 0, 0))
        archive.writestr(info, text)
    path.write_bytes(buffer.getvalue())
    path.with_name(path.name + ".CHECKSUM").write_text(f"{sha256_file(path)}  {path.name}\n", encoding="utf-8")


def generate_synthetic(out: Path, seed: int = 7, futures_from: str | None = None) -> None:
    """Random-walk prices and funding in the exact file formats. Never real data.
    `futures_from` (YYYY-MM) starts every futures series in that month, like the real
    monthly archive, which begins in 2020-01."""
    rng = random.Random(seed)
    out.mkdir(parents=True, exist_ok=True)
    (out / "SYNTHETIC").write_text("Synthetische Testdaten, kein Marktdatum.\n", encoding="utf-8")
    spot_start = utc_ms(2019, 1, 1)
    futures_start = {"BTCUSDT": utc_ms(2019, 9, 1), "ETHUSDT": utc_ms(2019, 11, 1)}
    if futures_from is not None:
        futures_start = {symbol: utc_ms(int(futures_from[:4]), int(futures_from[5:7]), 1) for symbol in SYMBOLS}
    hourly_sigma = 0.6 / math.sqrt(8760)
    for symbol, price in (("BTCUSDT", 4000.0), ("ETHUSDT", 150.0)):
        spot, perp, mark, index = {}, {}, {}, {}
        basis = 0.0003
        hour = spot_start
        while hour < WINDOW_END:
            close = price * math.exp(rng.gauss(0, hourly_sigma))
            wiggle = abs(rng.gauss(0, 0.002))
            spot[hour] = (price, max(price, close) * (1 + wiggle), min(price, close) * (1 - wiggle), close)
            basis = 0.0003 + 0.98 * (basis - 0.0003) + rng.gauss(0, 0.0003)
            o, c = price * (1 + basis), close * (1 + basis)
            perp[hour] = (o, max(o, c) * (1 + wiggle), min(o, c) * (1 - wiggle), c)
            noise = 1 + rng.gauss(0, 0.00005)
            mark[hour] = (o * noise, max(o, c) * noise * (1 + wiggle), min(o, c) * noise * (1 - wiggle), c * noise)
            index[hour] = (price, max(price, close) * (1 + wiggle / 2), min(price, close) * (1 - wiggle / 2), close)
            price = close
            hour += HOUR
        spot_dir = out / "spot"
        spot_dir.mkdir(parents=True, exist_ok=True)
        hourly_lines = [SPOT_HEADER] + [f"{hour},{hour + HOUR - 1},{o:.2f},{h:.2f},{low:.2f},{c:.2f},1" for hour, (o, h, low, c) in sorted(spot.items())]
        (spot_dir / f"{symbol}-1h.csv.gz").write_bytes(gzip.compress(("\n".join(hourly_lines) + "\n").encode(), mtime=0))
        daily_lines = [SPOT_HEADER]
        for day_ms in range(spot_start, WINDOW_END, DAY):
            bars = [spot[day_ms + k * HOUR] for k in range(24)]
            high, low = max(b[1] for b in bars), min(b[2] for b in bars)
            daily_lines.append(f"{day_ms},{day_ms + DAY - 1},{bars[0][0]:.2f},{high:.2f},{low:.2f},{bars[-1][3]:.2f},24")
        (spot_dir / f"{symbol}-1d.csv.gz").write_bytes(gzip.compress(("\n".join(daily_lines) + "\n").encode(), mtime=0))
        funding = []
        slot = futures_start[symbol]
        while slot < WINDOW_END:
            mean = SYNTHETIC_FUNDING_MEAN[_utc(slot).year] * (1.1 if symbol == "ETHUSDT" else 1.0)
            funding.append((slot + rng.randint(0, 9), mean + rng.gauss(0, 0.00004)))
            slot += 8 * HOUR
        funding_by_month: dict[str, list[tuple[int, float]]] = {}
        for t, r in funding:
            funding_by_month.setdefault(month_key(t), []).append((t, r))
        bars_by_month: dict[str, dict[str, list[tuple[int, Bar]]]] = {}
        for dataset, bars in (("klines", perp), ("markPriceKlines", mark), ("indexPriceKlines", index)):
            grouped = bars_by_month.setdefault(dataset, {})
            for t in sorted(bars):
                if t >= futures_start[symbol]:
                    grouped.setdefault(month_key(t), []).append((t, bars[t]))
        for month in months_between(month_key(futures_start[symbol]), LAST_MONTH):
            in_month = funding_by_month.get(month, [])
            text = "calc_time,funding_interval_hours,last_funding_rate\n" + "".join(f"{t},8,{r:.8f}\n" for t, r in in_month)
            _write_zip(dataset_dir(out, "fundingRate", symbol) / archive_name("fundingRate", symbol, month), f"{symbol}-fundingRate-{month}.csv", text)
            for dataset in ("klines", "markPriceKlines", "indexPriceKlines"):
                rows = bars_by_month[dataset].get(month, [])
                body = "".join(f"{t},{b[0]:.4f},{b[1]:.4f},{b[2]:.4f},{b[3]:.4f},1,{t + HOUR - 1},1,1,0,0,0\n" for t, b in rows)
                text = (KLINE_HEADER + "\n" + body) if month >= "2022-01" else body
                _write_zip(dataset_dir(out, dataset, symbol) / archive_name(dataset, symbol, month), f"{symbol}-1h-{month}.csv", text)
        rest_dir = out / "binance" / "rest"
        rest_dir.mkdir(parents=True, exist_ok=True)
        for month in REST_SAMPLE_MONTHS:
            items = [{"symbol": symbol, "fundingTime": t, "fundingRate": f"{r:.8f}", "markPrice": "0"} for t, r in funding if month_key(t) == month]
            (rest_dir / f"fundingRate-{symbol}-{month}.json").write_text(json.dumps(items), encoding="utf-8")
    fred = out / "fred"
    fred.mkdir(parents=True, exist_ok=True)
    lines = ["observation_date,DTB3"]
    for day_ms in range(utc_ms(2019, 12, 1), WINDOW_END, DAY):
        moment = _utc(day_ms)
        if moment.weekday() >= 5:
            continue
        level = 1.5 if moment.year < 2020 else 0.1 if moment.year < 2022 else 4.5 if moment.year < 2025 else 3.8
        lines.append(f"{moment:%Y-%m-%d},{'.' if rng.random() < 0.02 else f'{level + rng.gauss(0, 0.05):.2f}'}")
    (fred / "DTB3.csv").write_text("\n".join(lines) + "\n", encoding="utf-8")
    bench = ["month,champion,challenger"]
    for month in months_between("2018-04", LAST_MONTH):
        bench.append(f"{month},{rng.gauss(0.0, 0.003):.6f},{rng.gauss(0.002, 0.004):.6f}")
    (out / "benchmarks.csv").write_text("\n".join(bench) + "\n", encoding="utf-8")


