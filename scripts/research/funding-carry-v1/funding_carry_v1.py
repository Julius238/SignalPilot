# --- Reading files ------------------------------------------------------------


def _is_number(text: str) -> bool:
    try:
        float(text)
    except ValueError:
        return False
    return True


def normalize_timestamp(raw: str | int) -> int:
    """Milliseconds UTC; the archive switched some files to microseconds."""
    value = int(raw) if isinstance(raw, int) or str(raw).strip().lstrip("-").isdigit() else int(float(raw))
    if value >= 10**14:
        value //= 1000
    if value >= FORWARD_CUTOFF:
        raise ForwardDataError(f"Timestamp {iso(value)} is in the forward period (>= {iso(FORWARD_CUTOFF)}).")
    return value


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _csv_rows(text: str) -> tuple[list[str] | None, list[list[str]]]:
    rows = [row for row in csv.reader(io.StringIO(text)) if row and any(cell.strip() for cell in row)]
    if rows and not _is_number(rows[0][0]):
        return [cell.strip() for cell in rows[0]], rows[1:]
    return None, rows


def read_zip_csv(path: Path) -> tuple[list[str] | None, list[list[str]]]:
    with zipfile.ZipFile(path) as archive:
        names = [name for name in archive.namelist() if name.lower().endswith(".csv")]
        if len(names) != 1:
            raise StudyError(f"{path.name}: expected exactly one CSV, found {names}.")
        return _csv_rows(archive.read(names[0]).decode("utf-8"))


Bar = tuple[float, float, float, float]  # open, high, low, close


def parse_klines(path: Path) -> dict[int, Bar]:
    _, rows = read_zip_csv(path)
    bars: dict[int, Bar] = {}
    for row in rows:
        bars[normalize_timestamp(row[0])] = (float(row[1]), float(row[2]), float(row[3]), float(row[4]))
    return bars


@dataclass(frozen=True)
class RawFunding:
    calc_time: int
    interval_hours: int | None
    rate: float


def parse_funding(path: Path) -> list[RawFunding]:
    header, rows = read_zip_csv(path)
    if header is not None:
        index = {name: position for position, name in enumerate(header)}
        time_col = index.get("calc_time", index.get("fundingTime", 0))
        rate_col = index.get("last_funding_rate", index.get("fundingRate", len(header) - 1))
        interval_col = index.get("funding_interval_hours")
    else:
        time_col, rate_col = 0, len(rows[0]) - 1 if rows else 1
        interval_col = 1 if rows and len(rows[0]) >= 3 else None
    events = []
    for row in rows:
        interval = int(float(row[interval_col])) if interval_col is not None and row[interval_col].strip() else None
        events.append(RawFunding(normalize_timestamp(row[time_col]), interval, float(row[rate_col])))
    return events


def parse_spot_snapshot(path: Path) -> dict[int, Bar]:
    with gzip.open(path, "rt", encoding="utf-8") as handle:
        header = handle.readline().strip()
        if header != SPOT_HEADER:
            raise StudyError(f"{path.name}: unexpected snapshot header {header!r}.")
        bars: dict[int, Bar] = {}
        for line in handle:
            if not line.strip():
                continue
            parts = line.strip().split(",")
            open_time = int(parts[0])
            if open_time >= FORWARD_CUTOFF:
                continue  # the snapshot loader of the project drops forward candles the same way
            bars[open_time] = (float(parts[2]), float(parts[3]), float(parts[4]), float(parts[5]))
    return bars


def parse_dtb3(path: Path) -> dict[str, float]:
    """FRED DTB3 in percent; missing values ('.') are skipped."""
    header, rows = _csv_rows(path.read_text(encoding="utf-8"))
    if header is None:
        raise StudyError(f"{path.name}: missing header.")
    values = {}
    for row in rows:
        if len(row) >= 2 and row[1].strip() not in ("", "."):
            values[row[0].strip()] = float(row[1])
    return values


def parse_benchmarks(path: Path) -> tuple[dict[str, dict[str, float]], dict[str, dict[str, float]]]:
    """month,champion,challenger[,champion_binding,challenger_binding]: monthly simple returns
    from comparison A (§7) and, optionally, the average share of capital bound in that month."""
    header, rows = _csv_rows(path.read_text(encoding="utf-8"))
    if header is None or header[:3] != ["month", "champion", "challenger"]:
        raise StudyError(f"{path.name}: expected header month,champion,challenger[,champion_binding,challenger_binding].")
    with_binding = header[3:5] == ["champion_binding", "challenger_binding"]
    series: dict[str, dict[str, float]] = {"champion": {}, "challenger": {}}
    binding: dict[str, dict[str, float]] = {"champion": {}, "challenger": {}}
    for row in rows:
        series["champion"][row[0]] = float(row[1])
        series["challenger"][row[0]] = float(row[2])
        if with_binding:
            binding["champion"][row[0]] = float(row[3])
            binding["challenger"][row[0]] = float(row[4])
    return series, binding


# --- Archive discovery --------------------------------------------------------


def dataset_dir(data: Path, dataset: str, symbol: str) -> Path:
    base = data / "binance" / "futures" / "um" / "monthly" / dataset / symbol
    return base if dataset == "fundingRate" else base / "1h"


def archive_name(dataset: str, symbol: str, month: str) -> str:
    return f"{symbol}-fundingRate-{month}.zip" if dataset == "fundingRate" else f"{symbol}-1h-{month}.zip"


def months_between(first: str, last: str) -> list[str]:
    year, month = int(first[:4]), int(first[5:7])
    result = []
    while f"{year:04d}-{month:02d}" <= last:
        result.append(f"{year:04d}-{month:02d}")
        month += 1
        if month == 13:
            year, month = year + 1, 1
    return result


def present_months(data: Path, dataset: str, symbol: str) -> list[str]:
    directory = dataset_dir(data, dataset, symbol)
    if not directory.is_dir():
        return []
    prefix = archive_name(dataset, symbol, "")[: -len(".zip")]
    months = []
    for path in directory.glob("*.zip"):
        stem = path.name[: -len(".zip")]
        if stem.startswith(prefix) and len(stem) == len(prefix) + 7:
            months.append(stem[len(prefix):])
    return sorted(months)


def spot_dir_for(data: Path, spot: Path | None) -> Path:
    return spot if spot is not None else data / "spot"


# --- Data checks (§2.2) ---------------------------------------------------------


def check_files(data: Path) -> dict:
    """D1: every month from the first file to 2026-09 present, SHA-256 equals .CHECKSUM."""
    report: dict = {"passed": True, "series": {}, "fingerprint": None}
    lines = []
    for symbol in SYMBOLS:
        for dataset in FUTURES_DATASETS:
            months = present_months(data, dataset, symbol)
            entry: dict = {"first": months[0] if months else None, "missing": [], "badChecksum": [], "ignoredAfterWindow": []}
            if not months:
                entry["missing"] = ["(keine Datei)"]
            else:
                for month in [m for m in months if m > LAST_MONTH]:
                    entry["ignoredAfterWindow"].append(month)
                for month in months_between(months[0], LAST_MONTH):
                    path = dataset_dir(data, dataset, symbol) / archive_name(dataset, symbol, month)
                    if not path.exists():
                        entry["missing"].append(month)
                        continue
                    checksum = path.with_name(path.name + ".CHECKSUM")
                    actual = sha256_file(path)
                    expected = checksum.read_text(encoding="utf-8").split()[0].lower() if checksum.exists() else None
                    if expected != actual:
                        entry["badChecksum"].append(month)
                    lines.append(f"{dataset}/{symbol}/{month} {actual}")
            entry["passed"] = not entry["missing"] and not entry["badChecksum"]
            report["passed"] &= entry["passed"]
            report["series"][f"{dataset}/{symbol}"] = entry
    report["fingerprint"] = hashlib.sha256("\n".join(sorted(lines)).encode()).hexdigest() if lines else None
    return report


@dataclass(frozen=True)
class FundingEvent:
    slot: int  # settlement hour (calc_time floored to the full hour)
    rate: float
    interval_hours: int | None


def normalize_funding(raw: list[RawFunding], range_start: int, range_end: int) -> tuple[list[FundingEvent], dict]:
    """D2/D3/D7: one event per settlement slot; conflicting duplicates are dropped (booked as 0)."""
    by_slot: dict[int, list[RawFunding]] = {}
    for event in raw:
        by_slot.setdefault(event.calc_time - event.calc_time % HOUR, []).append(event)
    events: list[FundingEvent] = []
    duplicates = conflicts = 0
    for slot in sorted(by_slot):
        group = by_slot[slot]
        if len(group) > 1:
            if len({event.rate for event in group}) > 1:
                conflicts += 1
                continue
            duplicates += len(group) - 1
        events.append(FundingEvent(slot, group[0].rate, group[0].interval_hours))

    inside = [event for event in events if range_start <= event.slot < range_end]
    missing = irregular = interval_changes = 0
    longest_gap = 0
    for previous, current in zip(inside, inside[1:]):
        expected = (current.interval_hours or DEFAULT_FUNDING_INTERVAL_HOURS) * HOUR
        gap = current.slot - previous.slot
        if gap > expected:
            missing += max(0, round(gap / expected) - 1)
            longest_gap = max(longest_gap, (gap - expected) // HOUR)
        elif gap < expected:
            irregular += 1
        if current.interval_hours != previous.interval_hours:
            interval_changes += 1
    if inside:
        last = inside[-1]
        expected = (last.interval_hours or DEFAULT_FUNDING_INTERVAL_HOURS) * HOUR
        trailing = max(0, math.ceil((range_end - last.slot) / expected) - 1)
        missing += trailing
        if trailing:
            longest_gap = max(longest_gap, trailing * expected // HOUR)
    total = len(inside) + missing
    share = missing / total if total else 1.0
    base = [event for event in inside if (event.interval_hours or 8) == 8]
    report = {
        "range": [iso(range_start), iso(range_end)],
        "events": len(inside),
        "missing": missing,
        "missingShare": share,
        "longestGapHours": longest_gap,
        "duplicatesDropped": duplicates,
        "conflictingSlotsDropped": conflicts,
        "irregularSpacing": irregular,
        "passed": bool(inside) and share <= MAX_MISSING_SHARE and longest_gap <= MAX_GAP_HOURS,
        # D3: listed, never removed
        "outliers": [[iso(e.slot), e.rate] for e in inside if abs(e.rate) > FUNDING_OUTLIER],
        # D7: report only
        "baseRateShare": (sum(1 for e in base if abs(e.rate - BASE_RATE) < 1e-12) / len(base)) if base else None,
        "intervalChanges": interval_changes,
    }
    return events, report


def clean_bars(bars: dict[int, Bar]) -> tuple[dict[int, Bar], list[str]]:
    """Bars violating low <= open/close <= high count as missing (D4)."""
    clean, violations = {}, []
    for open_time, (o, h, low, c) in bars.items():
        if low <= min(o, c) and max(o, c) <= h and low > 0:
            clean[open_time] = (o, h, low, c)
        else:
            violations.append(iso(open_time))
    return clean, violations


def check_hourly(bars: dict[int, Bar], start: int, end: int, violations: list[str]) -> dict:
    expected = missing = run = longest = 0
    hour = start
    while hour < end:
        expected += 1
        if hour in bars:
            run = 0
        else:
            missing += 1
            run += 1
            longest = max(longest, run)
        hour += HOUR
    share = missing / expected if expected else 1.0
    return {
        "range": [iso(start), iso(end)],
        "expectedHours": expected,
        "missingHours": missing,
        "missingShare": share,
        "longestGapHours": longest,
        "ohlcViolations": len(violations),
        "ohlcViolationExamples": violations[:10],
        "passed": expected > 0 and share <= MAX_MISSING_SHARE and longest <= MAX_GAP_HOURS,
    }


@dataclass
class SymbolData:
    symbol: str
    funding: list[FundingEvent]
    perp: dict[int, Bar]
    mark: dict[int, Bar]
    index: dict[int, Bar]
    spot: dict[int, Bar]
    spot_daily: dict[int, Bar] | None
    start: int  # sleeve start (§2.1: first day with 7 days of funding history)


def sleeve_start(events: list[FundingEvent]) -> int:
    if not events:
        raise StudyError("No funding events.")
    first = events[0].slot
    if first <= WINDOW_START - FILTER_DAYS * DAY:
        return WINDOW_START
    ready = first + FILTER_DAYS * DAY
    return ready if ready % DAY == 0 else ready - ready % DAY + DAY


def load_futures(data: Path, dataset: str, symbol: str) -> dict[int, Bar] | list[RawFunding]:
    months = [m for m in present_months(data, dataset, symbol) if m <= LAST_MONTH]
    if dataset == "fundingRate":
        raw: list[RawFunding] = []
        for month in months:
            raw.extend(parse_funding(dataset_dir(data, dataset, symbol) / archive_name(dataset, symbol, month)))
        return raw
    bars: dict[int, Bar] = {}
    for month in months:
        bars.update(parse_klines(dataset_dir(data, dataset, symbol) / archive_name(dataset, symbol, month)))
    return bars


def check_rest_sample(data: Path, symbol: str, events: list[FundingEvent]) -> dict:
    """D6: REST sample of the first and last full month equals the archive."""
    by_slot = {event.slot: event.rate for event in events}
    report: dict = {"months": {}, "passed": True}
    for month in REST_SAMPLE_MONTHS:
        path = data / "binance" / "rest" / f"fundingRate-{symbol}-{month}.json"
        if not path.exists():
            report["months"][month] = {"performed": False}
            report["passed"] = False
            continue
        rest = {}
        for item in json.loads(path.read_text(encoding="utf-8")):
            time = normalize_timestamp(item["fundingTime"])
            rest[time - time % HOUR] = float(item["fundingRate"])
        archive = {slot: rate for slot, rate in by_slot.items() if month_key(slot) == month}
        union = sorted(set(rest) | set(archive))
        mismatches = [iso(slot) for slot in union if slot not in rest or slot not in archive or abs(rest[slot] - archive[slot]) > REST_TOLERANCE]
        share = len(mismatches) / len(union) if union else 1.0
        passed = bool(union) and share <= REST_MAX_MISMATCH_SHARE
        report["months"][month] = {"performed": True, "events": len(union), "mismatches": len(mismatches), "examples": mismatches[:10], "passed": passed}
        report["passed"] &= passed
    return report


def check_data(data: Path, spot: Path | None = None) -> tuple[dict, dict[str, SymbolData]]:
    """D1-D8. The report holds data quality only: no returns, no funding averages (§2.2)."""
    spot_dir = spot_dir_for(data, spot)
    report: dict = {"study": STUDY_KEY, "scriptVersion": SCRIPT_VERSION, "synthetic": (data / "SYNTHETIC").exists(), "checks": {}}
    d1 = check_files(data)
    report["checks"]["D1"] = d1
    loaded: dict[str, SymbolData] = {}
    d2: dict = {"passed": True, "symbols": {}}
    d4: dict = {"passed": True, "series": {}}
    d5: dict = {"symbols": {}}
    d6: dict = {"passed": True, "symbols": {}}
    d7: dict = {"symbols": {}}
    d8: dict = {"passed": True, "symbols": {}}
    for symbol in SYMBOLS:
        raw = load_futures(data, "fundingRate", symbol)
        first_slot = min((e.calc_time - e.calc_time % HOUR for e in raw), default=None)
        if first_slot is None:
            d2["symbols"][symbol] = {"passed": False, "reason": "keine Abrechnungen"}
            d2["passed"] = False
            continue
        range_start = max(WINDOW_START - FILTER_DAYS * DAY, first_slot)
        events, funding_report = normalize_funding(raw, range_start, WINDOW_END)
        start = sleeve_start(events)
        funding_report["sleeveStart"] = iso(start)
        d7["symbols"][symbol] = {"baseRateShare": funding_report.pop("baseRateShare"), "intervalChanges": funding_report.pop("intervalChanges")}
        d2["symbols"][symbol] = funding_report
        d2["passed"] &= funding_report["passed"]

        series = {}
        for dataset in ("klines", "markPriceKlines", "indexPriceKlines"):
            bars, violations = clean_bars(load_futures(data, dataset, symbol))
            series[dataset] = bars
            hourly = check_hourly(bars, start, WINDOW_END, violations)
            d4["series"][f"{dataset}/{symbol}"] = hourly
            d4["passed"] &= hourly["passed"]

        spot_path = spot_dir / f"{symbol}-1h.csv.gz"
        daily_path = spot_dir / f"{symbol}-1d.csv.gz"
        if spot_path.exists():
            spot_bars, spot_violations = clean_bars(parse_spot_snapshot(spot_path))
            spot_report = check_hourly(spot_bars, start, WINDOW_END, spot_violations)
            spot_report["sha256"] = sha256_file(spot_path)
        else:
            spot_bars, spot_report = {}, {"passed": False, "reason": f"{spot_path} fehlt"}
        spot_daily = parse_spot_snapshot(daily_path) if daily_path.exists() else None
        spot_report["dailySnapshot"] = sha256_file(daily_path) if daily_path.exists() else None
        d8["symbols"][symbol] = spot_report
        d8["passed"] &= spot_report["passed"]

        basis_flags, mark_flags = [], []
        hour = start
        while hour < WINDOW_END:
            p, s = series["klines"].get(hour), spot_bars.get(hour)
            m, i = series["markPriceKlines"].get(hour), series["indexPriceKlines"].get(hour)
            if p and s and abs(p[3] / s[3] - 1) > BASIS_FLAG:
                basis_flags.append(iso(hour))
            if m and i and abs(m[3] / i[3] - 1) > MARK_INDEX_FLAG:
                mark_flags.append(iso(hour))
            hour += HOUR
        d5["symbols"][symbol] = {"perpVsSpot": len(basis_flags), "perpVsSpotExamples": basis_flags[:20], "markVsIndex": len(mark_flags), "markVsIndexExamples": mark_flags[:20]}

        d6["symbols"][symbol] = check_rest_sample(data, symbol, events)
        d6["passed"] &= d6["symbols"][symbol]["passed"]

        loaded[symbol] = SymbolData(symbol, events, series["klines"], series["markPriceKlines"], series["indexPriceKlines"], spot_bars, spot_daily, start)

    report["checks"].update({"D2": d2, "D3": {sym: d2["symbols"].get(sym, {}).get("outliers") for sym in SYMBOLS}, "D4": d4, "D5": d5, "D6": d6, "D7": d7, "D8": d8})
    for symbol in SYMBOLS:
        d2["symbols"].get(symbol, {}).pop("outliers", None)
    report["blockingPassed"] = all(report["checks"][check]["passed"] for check in BLOCKING_CHECKS)
    report["dataFingerprint"] = d1["fingerprint"]
    return report, loaded


