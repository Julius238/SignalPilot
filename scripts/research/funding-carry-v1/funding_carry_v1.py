def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=f"{STUDY_KEY} ({SCRIPT_VERSION})")
    commands = parser.add_subparsers(dest="command", required=True)
    synth = commands.add_parser("synth", help="synthetic data in the archive layout")
    synth.add_argument("--out", type=Path, required=True)
    synth.add_argument("--seed", type=int, default=7)
    synth.add_argument("--futures-from", help="YYYY-MM: start of every futures series (the real archive starts 2020-01)")
    check = commands.add_parser("check-data", help="data checks D1-D8, no returns")
    check.add_argument("--data", type=Path, required=True)
    check.add_argument("--spot", type=Path)
    check.add_argument("--out", type=Path)
    run = commands.add_parser("evaluate", help="one run of both variants")
    run.add_argument("--data", type=Path, required=True)
    run.add_argument("--spot", type=Path)
    run.add_argument("--benchmarks", type=Path, required=True)
    run.add_argument("--out", type=Path, required=True)
    run.add_argument("--venue-status", default="OFFEN", choices=VENUE_STATUSES)
    run.add_argument("--correction")
    args = parser.parse_args(argv)
    try:
        if args.command == "synth":
            generate_synthetic(args.out, args.seed, args.futures_from)
            print(f"Synthetic data written to {args.out}")
            return 0
        if args.command == "check-data":
            report, _ = check_data(args.data, args.spot)
            if args.out:
                args.out.write_text(json.dumps(report, indent=2, ensure_ascii=False), encoding="utf-8")
            print(render_data_report(report))
            return 0 if report["blockingPassed"] else 2
        report = evaluate(args.data, args.benchmarks, args.out, args.spot, args.venue_status, args.correction)
        print(f"Ergebnisklasse: {report['outcome']}")
        return 0 if report["outcome"] != "NICHT_AUSWERTBAR" else 2
    except StudyError as error:
        print(f"Abgebrochen: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
