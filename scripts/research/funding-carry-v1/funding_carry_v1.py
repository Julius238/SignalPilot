def render_data_report(report: dict) -> str:
    lines = [f"# {STUDY_KEY}: Datenprüfung", ""]
    if report["synthetic"]:
        lines += ["> **SYNTHETISCHE DATEN.**", ""]
    lines += [f"- Blockierende Prüfungen bestanden: **{'ja' if report['blockingPassed'] else 'nein'}**",
              f"- Daten-Fingerprint: `{report['dataFingerprint']}`", "", "| Prüfung | bestanden |", "|---|---|"]
    for check in BLOCKING_CHECKS:
        lines.append(f"| {check} | {'ja' if report['checks'][check]['passed'] else 'nein'} |")
    lines += ["", "Details (D3, D5, D7 nur Bericht) stehen in der JSON-Datei.", ""]
    return "\n".join(lines)


