@dataclass
class Series:
    """A daily equity curve with its cash-flow attribution (one sleeve or the sum)."""

    start_equity: float
    daily: list[tuple[str, float]]
    hourly: list[float]
    funding_by_day: dict[str, float]
    costs_by_day: dict[str, float]
    legging_by_day: dict[str, float]


def sleeve_series(result: SleeveResult) -> Series:
    padded = _pad_daily(result.daily, result.start_equity)
    return Series(result.start_equity, padded, [equity for _, equity in result.hourly], result.funding_by_day, result.costs_by_day, result.legging_by_day)


def _window_days() -> list[str]:
    days, ms = [], WINDOW_START
    while ms < WINDOW_END:
        days.append(day_key(ms))
        ms += DAY
    return days


def _pad_daily(daily: list[tuple[str, float]], capital: float) -> list[tuple[str, float]]:
    values = dict(daily)
    padded, last = [], capital
    for day in _window_days():
        last = values.get(day, last)
        padded.append((day, last))
    return padded


def combine(results: list[SleeveResult]) -> Series:
    curves = [dict(_pad_daily(result.daily, result.start_equity)) for result in results]
    daily = [(day, sum(curve[day] for curve in curves)) for day in _window_days()]
    hourly_maps = [dict(result.hourly) for result in results]
    hours, hourly = sorted(set().union(*hourly_maps)), []
    lasts = [result.start_equity for result in results]
    for hour in hours:
        for index, mapping in enumerate(hourly_maps):
            lasts[index] = mapping.get(hour, lasts[index])
        hourly.append(sum(lasts))

    def merged(name: str) -> dict[str, float]:
        total: dict[str, float] = {}
        for result in results:
            for day, value in getattr(result, name).items():
                total[day] = total.get(day, 0.0) + value
        return total

    return Series(sum(r.start_equity for r in results), daily, hourly, merged("funding_by_day"), merged("costs_by_day"), merged("legging_by_day"))


def series_metrics(series: Series, rf_by_day: dict[str, float] | None = None) -> dict:
    daily = series.daily
    first_day, last_day = daily[0][0], daily[-1][0]
    final = daily[-1][1]
    sub_first = day_key(SUBPERIOD_START)
    start_sub = _equity_at(daily, day_key(SUBPERIOD_START - DAY), series.start_equity)
    sub_days = sum(1 for day, _ in daily if day >= sub_first)

    def decomposition(start_equity: float, end_equity: float, first: str, last: str) -> dict:
        funding = _sum_between(series.funding_by_day, first, last)
        costs = _sum_between(series.costs_by_day, first, last)
        legging = _sum_between(series.legging_by_day, first, last)
        return {"pnl": end_equity - start_equity, "funding": funding, "executionCosts": costs, "leggingLoss": legging,
                "basisAndValuation": end_equity - start_equity - funding + costs + legging}

    returns, previous = [], series.start_equity
    for _, equity in daily:
        returns.append(equity / previous - 1)
        previous = equity
    sd = statistics.stdev(returns) if len(returns) > 1 else 0.0
    months = monthly_returns(daily, series.start_equity)
    month_values = list(months.values())
    monthly_sd = statistics.stdev(month_values) if len(month_values) > 1 else 0.0
    years, previous = {}, series.start_equity
    for year in CALENDAR_YEARS:
        end_equity = _equity_at(daily, f"{year}-12-31", previous)
        years[str(year)] = {"return": end_equity / previous - 1 if previous > 0 else None,
                            **decomposition(previous, end_equity, f"{year}-01-01", f"{year}-12-31")}
        year_points = [equity for day, equity in daily if day.startswith(str(year))]
        years[str(year)]["maxDrawdown"] = max_drawdown(year_points, previous) if year_points else None
        previous = end_equity
    month_ends = sorted({day[:7]: (day, equity) for day, equity in daily}.values())
    rolling = []
    for index in range(12, len(month_ends)):
        rolling.append([month_ends[index][0][:7], month_ends[index][1] / month_ends[index - 12][1] - 1])

    total_cagr = cagr(series.start_equity, final, len(daily))
    sub_cagr = cagr(start_sub, final, sub_days)
    metrics = {
        "window": [first_day, last_day],
        "startEquity": series.start_equity,
        "finalEquity": final,
        "netPerYear": total_cagr,
        "netPerYearSince2024": sub_cagr,
        "netPerYear2020To2023": cagr(series.start_equity, start_sub, len(daily) - sub_days),
        "decomposition": decomposition(series.start_equity, final, first_day, last_day),
        "decompositionSince2024": decomposition(start_sub, final, sub_first, last_day),
        "sharpeDaily": statistics.fmean(returns) / sd * math.sqrt(365) if sd > 0 else None,
        "sharpeMonthly": statistics.fmean(month_values) / monthly_sd * math.sqrt(12) if monthly_sd > 0 else None,
        "maxDrawdownDaily": max_drawdown([equity for _, equity in daily], series.start_equity),
        "maxDrawdownHourly": max_drawdown(series.hourly, series.start_equity) if series.hourly else None,
        "worstMonth": min(month_values) if month_values else None,
        "negativeMonthShare": sum(1 for value in month_values if value < 0) / len(month_values) if month_values else None,
        "positiveYears": sum(1 for year in years.values() if (year["return"] or 0) > 0),
        "calendarYears": years,
        "rolling12Months": rolling,
        "monthlyReturns": months,
        "netAfterHaircut": total_cagr - HAIRCUT,
        "netAfterHaircutSince2024": sub_cagr - HAIRCUT,
        "netAfterPessimisticHaircut": total_cagr - HAIRCUT_PESSIMISTIC,
        "netAfterPessimisticHaircutSince2024": sub_cagr - HAIRCUT_PESSIMISTIC,
    }
    if rf_by_day is not None:
        rf_total = mean_rate(rf_by_day, first_day, last_day)
        rf_sub = mean_rate(rf_by_day, sub_first, last_day)
        metrics.update({"riskFreeMean": rf_total, "riskFreeMeanSince2024": rf_sub,
                        "excessAfterHaircut": total_cagr - HAIRCUT - rf_total,
                        "excessAfterHaircutSince2024": sub_cagr - HAIRCUT - rf_sub})
    return metrics


def mean_rate(rf_by_day: dict[str, float], first: str, last: str) -> float:
    values = [value for day, value in rf_by_day.items() if first <= day <= last]
    if not values:
        raise StudyError(f"DTB3 has no observation between {first} and {last}.")
    return statistics.fmean(values) / 100


def daily_funding(events: list[tuple[int, float]]) -> dict[str, float]:
    by_day = {day: 0.0 for day in _window_days()}
    for slot, rate in events:
        day = day_key(slot)
        if day in by_day:
            by_day[day] += rate
    return by_day


def funding_statistics(events: list[tuple[int, float]]) -> dict:
    """M6, M8 (funding part) and M12: independent of the variant."""
    by_day = daily_funding(events)
    slots = [slot for slot, _ in events]
    prefix = [0.0]
    for _, rate in events:
        prefix.append(prefix[-1] + rate)

    def s7(decision: int) -> float:
        return prefix[bisect.bisect_left(slots, decision)] - prefix[bisect.bisect_left(slots, decision - FILTER_DAYS * DAY)]

    s7_by_day = {}
    ms = WINDOW_START
    while ms < WINDOW_END:
        s7_by_day[day_key(ms)] = s7(ms)
        ms += DAY
    month_sums: dict[str, float] = {}
    for day, value in by_day.items():
        month_sums[day[:7]] = month_sums.get(day[:7], 0.0) + value
    inside = [(slot, rate) for slot, rate in events if WINDOW_START <= slot < WINDOW_END]
    per_year = {}
    for year in CALENDAR_YEARS:
        days = [day for day in by_day if day.startswith(str(year))]
        annualized = [by_day[day] * 365 for day in days]
        rates = [rate for slot, rate in inside if day_key(slot).startswith(str(year))]
        streak = longest = 0
        for day in days:
            streak = streak + 1 if s7_by_day[day] <= FILTER_THRESHOLD else 0
            longest = max(longest, streak)
        window = [by_day[day] for day in days]
        worst30 = min((sum(window[i:i + 30]) for i in range(0, max(1, len(window) - 29))), default=None)
        per_year[str(year)] = {
            "meanAnnualized": statistics.fmean(annualized) if annualized else None,
            "medianAnnualized": statistics.median(annualized) if annualized else None,
            "stdevAnnualized": statistics.stdev(annualized) if len(annualized) > 1 else None,
            "negativeSettlementShare": sum(1 for r in rates if r < 0) / len(rates) if rates else None,
            "longestDaysS7NotPositive": longest,
            "worst30DaySum": worst30,
            "shareDaysS7Positive": sum(1 for day in days if s7_by_day[day] > FILTER_THRESHOLD) / len(days) if days else None,
        }
    return {
        "negativeFundingMonthShare": sum(1 for v in month_sums.values() if v < 0) / len(month_sums) if month_sums else None,
        "negativeFundingMonths": sorted(month for month, value in month_sums.items() if value < 0),
        "perYear": per_year,
    }


def basis_statistics(data: SymbolData) -> dict:
    """M13 (distribution part): (perp ÷ spot − 1) at hourly closes."""
    values, by_month = [], {}
    hour = data.start
    while hour < WINDOW_END:
        p, s = data.perp.get(hour), data.spot.get(hour)
        if p and s:
            basis = p[3] / s[3] - 1
            values.append(basis)
            low, high = by_month.get(month_key(hour), (basis, basis))
            by_month[month_key(hour)] = (min(low, basis), max(high, basis))
        hour += HOUR
    if not values:
        return {}
    ordered = sorted(values)

    def quantile(q: float) -> float:
        return ordered[min(len(ordered) - 1, max(0, round(q * (len(ordered) - 1))))]

    widest = max(by_month.items(), key=lambda item: item[1][1] - item[1][0])
    return {"median": statistics.median(values), "p01": quantile(0.01), "p99": quantile(0.99), "min": ordered[0], "max": ordered[-1],
            "largestMonthlyRange": {"month": widest[0], "range": widest[1][1] - widest[1][0]}}


def one_leg_scenario(data: SymbolData) -> dict:
    """M18 (L24): largest |24h change| × leg share 0.5, as a loss of the sleeve capital."""
    worst, when = 0.0, None
    hour = data.start
    while hour + 24 * HOUR < WINDOW_END:
        now, later = data.spot.get(hour), data.spot.get(hour + 24 * HOUR)
        if now and later:
            change = abs(later[3] / now[3] - 1)
            if change > worst:
                worst, when = change, iso(hour + HOUR)
        hour += HOUR
    return {"largest24hChange": worst, "lossOfSleeveCapital": 0.5 * worst, "from": when}


def spot_monthly_returns(spot: dict[int, Bar]) -> dict[str, float]:
    month_end: dict[str, float] = {}
    previous_close = None
    for hour in sorted(spot):
        if hour < WINDOW_START - DAY:
            continue
        if hour < WINDOW_START:
            previous_close = spot[hour][3]
            continue
        if hour >= WINDOW_END:
            break
        month_end[month_key(hour)] = spot[hour][3]
    result = {}
    for month in sorted(month_end):
        if previous_close:
            result[month] = month_end[month] / previous_close - 1
        previous_close = month_end[month]
    return result


def _js_round(value: float) -> float:
    return math.floor(value * 100 + 0.5) / 100


def regime_labels(btc_daily: dict[int, Bar], eth_daily: dict[int, Bar]) -> dict[str, str]:
    """Re-implementation of crypto-native-regime-v1/1.0.0 (market-regime, calculateCryptoNativeRegimeReport).
    The label of day D uses daily candles opened before D (no look-ahead). Report only (M21)."""

    def summary(closes: list[float], count: int) -> dict | None:
        """The first `count` closes, as summarizeBenchmark sees them."""
        if count < 200:
            return None
        last = closes[count - 1]
        sma50 = sum(closes[count - 50:count]) / 50
        sma200 = sum(closes[count - 200:count]) / 200
        previous = closes[count - 21]
        performance = (last - previous) / previous * 100 if previous else None
        momentum = "UNKNOWN" if performance is None else "POSITIVE" if performance > 1 else "NEGATIVE" if performance < -1 else "NEUTRAL"
        return {"vs50": _js_round((last - sma50) / sma50 * 100), "vs200": _js_round((last - sma200) / sma200 * 100), "momentum": momentum}

    btc_times, eth_times = sorted(btc_daily), sorted(eth_daily)
    btc_closes, eth_closes = [btc_daily[t][3] for t in btc_times], [eth_daily[t][3] for t in eth_times]
    labels = {}
    for day_ms in range(WINDOW_START, WINDOW_END, DAY):
        btc = summary(btc_closes, bisect.bisect_left(btc_times, day_ms))
        eth = summary(eth_closes, bisect.bisect_left(eth_times, day_ms))
        if btc is None or eth is None or btc["momentum"] == "UNKNOWN" or eth["momentum"] == "UNKNOWN":
            label = "UNKNOWN"
        elif btc["vs200"] > 0 and btc["vs50"] > 0 and btc["momentum"] != "NEGATIVE" and eth["vs50"] > 0:
            label = "RISK_ON"
        elif not btc["vs200"] > 0 and btc["vs50"] < 0:
            label = "RISK_OFF"
        elif (btc["vs50"] > 0) != (eth["vs50"] > 0):
            label = "MIXED"
        else:
            label = "NEUTRAL"
        labels[day_key(day_ms)] = label
    return labels


