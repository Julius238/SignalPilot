def student_t975(df: float) -> float:
    """Cornish-Fisher expansion, identical to studentT975 in packages/evolution/src/paired.ts."""
    if not math.isfinite(df) or df < 3:
        raise StudyError(f"Student-t quantile needs at least 3 degrees of freedom, got {df}.")
    z = 1.959963984540054
    g1 = (z**3 + z) / 4
    g2 = (5 * z**5 + 16 * z**3 + 3 * z) / 96
    g3 = (3 * z**7 + 19 * z**5 + 17 * z**3 - 15 * z) / 384
    g4 = (79 * z**9 + 776 * z**7 + 1482 * z**5 - 1920 * z**3 - 945 * z) / 92160
    return z + g1 / df + g2 / df**2 + g3 / df**3 + g4 / df**4


def newey_west_lag(n: int) -> int:
    return max(1, math.floor(4 * (n / 100) ** (2 / 9)))


def _solve(matrix: list[list[float]], vector: list[float]) -> list[float] | None:
    n = len(vector)
    a = [row[:] + [vector[index]] for index, row in enumerate(matrix)]
    for column in range(n):
        pivot = max(range(column, n), key=lambda row: abs(a[row][column]))
        scale = max(max(abs(row[column]) for row in a), 1e-300)
        if abs(a[pivot][column]) <= 1e-12 * scale:
            return None
        a[column], a[pivot] = a[pivot], a[column]
        for row in range(column + 1, n):
            factor = a[row][column] / a[column][column]
            for k in range(column, n + 1):
                a[row][k] -= factor * a[column][k]
    x = [0.0] * n
    for row in range(n - 1, -1, -1):
        total = a[row][n] - sum(a[row][k] * x[k] for k in range(row + 1, n))
        x[row] = total / a[row][row]
    return x


def _invert(matrix: list[list[float]]) -> list[list[float]] | None:
    n = len(matrix)
    columns = []
    for index in range(n):
        column = _solve(matrix, [1.0 if k == index else 0.0 for k in range(n)])
        if column is None:
            return None
        columns.append(column)
    return [[columns[col][row] for col in range(n)] for row in range(n)]


def ols_hac(y: list[float], x_rows: list[list[float]]) -> dict | None:
    """OLS with max(iid, Newey-West) standard errors, as spanningAlphaTest (paired.ts)."""
    n, p = len(y), len(x_rows[0]) if x_rows else 0
    if n - p < 3:
        return None
    xtx = [[sum(row[i] * row[j] for row in x_rows) for j in range(p)] for i in range(p)]
    xty = [sum(row[i] * value for row, value in zip(x_rows, y)) for i in range(p)]
    coefficients = _solve(xtx, xty)
    inverse = _invert(xtx)
    if coefficients is None or inverse is None:
        return None
    residuals = [value - sum(c * v for c, v in zip(coefficients, row)) for row, value in zip(x_rows, y)]
    rss = sum(r * r for r in residuals)
    tss = sum(value * value for value in y)
    lag = min(newey_west_lag(n), n - 1)
    meat = [[0.0] * p for _ in range(p)]
    for t in range(n):
        for i in range(p):
            for j in range(p):
                meat[i][j] += residuals[t] ** 2 * x_rows[t][i] * x_rows[t][j]
    for lag_step in range(1, lag + 1):
        weight = 1 - lag_step / (lag + 1)
        for t in range(lag_step, n):
            product = residuals[t] * residuals[t - lag_step]
            for i in range(p):
                for j in range(p):
                    meat[i][j] += weight * product * (x_rows[t][i] * x_rows[t - lag_step][j] + x_rows[t - lag_step][i] * x_rows[t][j])
    iid_se, hac_se = [], []
    for k in range(p):
        iid_se.append(math.sqrt(max(0.0, rss / (n - p) * inverse[k][k])))
        hac = sum(inverse[k][i] * meat[i][j] * inverse[j][k] for i in range(p) for j in range(p))
        hac_se.append(math.sqrt(max(0.0, hac)))
    return {"n": n, "p": p, "coefficients": coefficients, "iidStandardError": iid_se, "hacStandardError": hac_se,
            "standardError": [max(a, b) for a, b in zip(iid_se, hac_se)], "lag": lag, "rss": rss, "tss": tss}


def spanning_alpha(candidate: dict[str, float], factors: list[dict[str, float]], months: list[str]) -> dict:
    """α of r_c = α + Σ βk·rk + ε; t uses max(iid, HAC) (spanningAlphaTest, paired.ts)."""
    rows = [(candidate[m], [1.0] + [f[m] for f in factors]) for m in months if m in candidate and all(m in f for f in factors)]
    n, p = len(rows), len(factors) + 1
    result: dict = {"months": n, "informativeMonths": sum(1 for y, _ in rows if abs(y) > 1e-12), "alpha": None, "tStat": None,
                    "criticalT": None, "standardError": None, "lag": newey_west_lag(n) if n else None, "betas": None}
    fit = ols_hac([y for y, _ in rows], [x for _, x in rows]) if rows else None
    if fit is None:
        return result
    explained = fit["rss"] <= 1e-18 * max(fit["tss"], 1e-300)
    se = fit["standardError"][0]
    result.update({"alpha": fit["coefficients"][0], "standardError": se, "iidStandardError": fit["iidStandardError"][0],
                   "hacStandardError": fit["hacStandardError"][0], "lag": fit["lag"],
                   "tStat": None if explained or se <= 1e-15 else fit["coefficients"][0] / se,
                   "criticalT": student_t975(n - p), "betas": fit["coefficients"][1:]})
    return result


def pearson(a: list[float], b: list[float]) -> float | None:
    if len(a) < 3:
        return None
    mean_a, mean_b = statistics.fmean(a), statistics.fmean(b)
    cov = sum((x - mean_a) * (y - mean_b) for x, y in zip(a, b))
    var_a = sum((x - mean_a) ** 2 for x in a)
    var_b = sum((y - mean_b) ** 2 for y in b)
    return cov / math.sqrt(var_a * var_b) if var_a > 0 and var_b > 0 else None


def _ranks(values: list[float]) -> list[float]:
    order = sorted(range(len(values)), key=lambda index: values[index])
    ranks = [0.0] * len(values)
    position = 0
    while position < len(order):
        end = position
        while end + 1 < len(order) and values[order[end + 1]] == values[order[position]]:
            end += 1
        for k in range(position, end + 1):
            ranks[order[k]] = (position + end) / 2 + 1
        position = end + 1
    return ranks


def spearman(a: list[float], b: list[float]) -> float | None:
    return pearson(_ranks(a), _ranks(b)) if len(a) >= 3 else None


def cagr(start: float, end: float, days: int) -> float:
    if start <= 0 or end <= 0 or days <= 0:
        return -1.0
    return (end / start) ** (365.25 / days) - 1


def max_drawdown(values: list[float], start: float | None = None) -> float:
    peak = start if start is not None else (values[0] if values else 0.0)
    worst = 0.0
    for value in values:
        peak = max(peak, value)
        if peak > 0:
            worst = max(worst, 1 - value / peak)
    return worst


def monthly_returns(daily: list[tuple[str, float]], start_equity: float) -> dict[str, float]:
    """Month-end equity over the previous month-end; the first month from the start equity (monthlyReturns, paired.ts)."""
    month_end: dict[str, float] = {}
    for day, equity in daily:
        month_end[day[:7]] = equity
    result, previous = {}, start_equity
    for month in sorted(month_end):
        if previous > 0:
            result[month] = month_end[month] / previous - 1
        previous = month_end[month]
    return result


def _equity_at(daily: list[tuple[str, float]], day: str, default: float) -> float:
    value = default
    for point_day, equity in daily:
        if point_day > day:
            break
        value = equity
    return value


def _sum_between(by_day: dict[str, float], first: str, last: str) -> float:
    return sum(value for day, value in by_day.items() if first <= day <= last)


