def run_variant(variant: str, loaded: dict[str, SymbolData], benchmarks: dict[str, dict[str, float]], rf_by_day: dict[str, float],
                btc_monthly: dict[str, float]) -> dict:
    markets = {symbol: market_for(data) for symbol, data in loaded.items()}
    base = {symbol: simulate(market, RunConfig(variant)) for symbol, market in markets.items()}
    stress = {symbol: simulate(market, RunConfig(variant, cost_multiplier=COST_STRESS_MULTIPLIER)) for symbol, market in markets.items()}
    legging = {symbol: simulate(market, RunConfig(variant, legging=True)) for symbol, market in markets.items()}
    maker = {symbol: simulate(market, RunConfig(variant, perp_cost=PERP_MAKER_COST)) for symbol, market in markets.items()}
    total_series = combine(list(base.values()))
    total = series_metrics(total_series, rf_by_day)
    # Hedged means the whole sleeve capital is bound (§5); flat sleeves hold cash.
    total["capitalBinding"] = statistics.fmean(r.hours_in_market / r.hours_total for r in base.values() if r.hours_total)
    total["netOverCapitalBinding"] = _ratio(total["netPerYear"], total["capitalBinding"])
    total["netOverMaxDrawdown"] = _ratio(total["netPerYear"], total["maxDrawdownDaily"])
    months = _months_in_window()
    candidate = total["monthlyReturns"]
    factors = [benchmarks["champion"], benchmarks["challenger"]]
    first_months = [m for m in months if m < month_key(SUBPERIOD_START)]
    later_months = [m for m in months if m >= month_key(SUBPERIOD_START)]
    common = [m for m in months if m in candidate and m in benchmarks["challenger"] and m in benchmarks["champion"]]
    btc_common = [m for m in months if m in candidate and m in btc_monthly]
    beta_fit = ols_hac([candidate[m] for m in btc_common], [[1.0, btc_monthly[m]] for m in btc_common]) if btc_common else None

    def summary(results: dict[str, SleeveResult]) -> dict:
        series = combine(list(results.values()))
        start, final = series.start_equity, series.daily[-1][1]
        return {"startEquity": start, "finalEquity": final, "netPerYear": cagr(start, final, len(series.daily))}

    legging_summary = summary(legging)
    legging_summary["largestSingleLoss"] = max(result.max_legging_loss for result in legging.values())
    sleeves = {}
    for symbol, result in base.items():
        metrics = series_metrics(sleeve_series(result))
        sleeves[symbol] = {
            "start": iso(result.start), "startEquity": result.start_equity, "finalEquity": result.final_equity,
            "netPerYear": metrics["netPerYear"], "netPerYearSince2024": metrics["netPerYearSince2024"],
            "decomposition": metrics["decomposition"], "maxDrawdownDaily": metrics["maxDrawdownDaily"],
            "entries": result.entries, "exits": result.exits, "rehedges": result.rehedges, "rebalances": result.rebalances,
            "liquidations": result.liquidations, "timeInMarket": result.hours_in_market / result.hours_total if result.hours_total else None,
            "costsOverGrossFunding": (metrics["decomposition"]["executionCosts"] / metrics["decomposition"]["funding"]) if metrics["decomposition"]["funding"] else None,
            "maxLeverage": result.max_leverage, "minLiquidationDistance": result.min_liquidation_distance,
            "minEuCloseOutDistance": result.min_eu_close_out_distance,
        }
    return {
        "key": VARIANT_KEYS[variant],
        "total": total,
        "sleeves": sleeves,
        "liquidations": sum(len(result.liquidations) for result in base.values()),
        "costStress": summary(stress),
        "legging": legging_summary,
        "perpMaker": summary(maker),
        "alpha": spanning_alpha(candidate, factors, months),
        "alphaFirstPeriod": spanning_alpha(candidate, factors, first_months),
        "alphaSince2024": spanning_alpha(candidate, factors, later_months),
        "correlation": {
            "months": len(common),
            "challengerPearson": pearson([candidate[m] for m in common], [benchmarks["challenger"][m] for m in common]),
            "challengerSpearman": spearman([candidate[m] for m in common], [benchmarks["challenger"][m] for m in common]),
            "championPearson": pearson([candidate[m] for m in common], [benchmarks["champion"][m] for m in common]),
            "championSpearman": spearman([candidate[m] for m in common], [benchmarks["champion"][m] for m in common]),
        },
        "btcBeta": None if beta_fit is None else {"beta": beta_fit["coefficients"][1], "tStat": beta_fit["coefficients"][1] / beta_fit["standardError"][1] if beta_fit["standardError"][1] > 0 else None},
    }


def _ratio(numerator: float | None, denominator: float | None) -> float | None:
    return numerator / denominator if numerator is not None and denominator else None


def benchmark_summary(benchmarks: dict[str, dict[str, float]], binding: dict[str, dict[str, float]], months: list[str],
                      btc_monthly: dict[str, float]) -> dict:
    """Comparison table (§7): champion and challenger on their 20 000-USDT slots, monthly basis."""
    result = {}
    for name, series in benchmarks.items():
        values = [series[m] for m in months if m in series]
        equity, curve = 1.0, []
        for value in values:
            equity *= 1 + value
            curve.append(equity)
        sd = statistics.stdev(values) if len(values) > 1 else 0.0
        net = equity ** (12 / len(values)) - 1 if values else None
        drawdown = max_drawdown(curve, 1.0)
        bound = [binding[name][m] for m in months if m in binding.get(name, {})]
        common = [m for m in months if m in series and m in btc_monthly]
        beta_fit = ols_hac([series[m] for m in common], [[1.0, btc_monthly[m]] for m in common]) if common else None
        result[name] = {"months": len(values), "netPerYear": net,
                        "sharpeMonthly": statistics.fmean(values) / sd * math.sqrt(12) if sd > 0 else None,
                        "maxDrawdownMonthEnd": drawdown, "worstMonth": min(values) if values else None,
                        "netOverMaxDrawdown": _ratio(net, drawdown),
                        "capitalBinding": statistics.fmean(bound) if bound else None,
                        "netOverCapitalBinding": _ratio(net, statistics.fmean(bound)) if bound else None,
                        "btcBeta": beta_fit["coefficients"][1] if beta_fit else None}
    common = [m for m in months if m in benchmarks["champion"] and m in benchmarks["challenger"]]
    result["champion"]["challengerPearson"] = pearson([benchmarks["champion"][m] for m in common], [benchmarks["challenger"][m] for m in common])
    return result


def portfolio_comparison(benchmarks: dict[str, dict[str, float]], carry: dict[str, float], months: list[str]) -> dict:
    """Report only (§7): A = champion + challenger + cash slot, B = the same with carry on the cash slot."""

    def curve(include_carry: bool) -> list[float]:
        slots = {"champion": 20_000.0, "challenger": 20_000.0, "third": 20_000.0}
        values = []
        for month in months:
            slots["champion"] *= 1 + benchmarks["champion"].get(month, 0.0)
            slots["challenger"] *= 1 + benchmarks["challenger"].get(month, 0.0)
            if include_carry:
                slots["third"] *= 1 + carry.get(month, 0.0)
            values.append(sum(slots.values()))
        return values

    def stats(values: list[float]) -> dict:
        returns = [values[0] / 60_000 - 1] + [b / a - 1 for a, b in zip(values, values[1:])]
        sd = statistics.stdev(returns)
        return {"netPerYear": (values[-1] / 60_000) ** (12 / len(values)) - 1, "sharpeMonthly": statistics.fmean(returns) / sd * math.sqrt(12) if sd > 0 else None,
                "maxDrawdownMonthEnd": max_drawdown(values, 60_000)}

    a, b = stats(curve(False)), stats(curve(True))
    return {"A": a, "B": b, "deltaNetPerYear": b["netPerYear"] - a["netPerYear"],
            "deltaSharpe": (b["sharpeMonthly"] - a["sharpeMonthly"]) if a["sharpeMonthly"] and b["sharpeMonthly"] else None,
            "deltaMaxDrawdown": b["maxDrawdownMonthEnd"] - a["maxDrawdownMonthEnd"]}


def evaluate(data: Path, benchmarks_path: Path, out: Path, spot: Path | None = None, venue_status: str = "OFFEN",
             correction: str | None = None) -> dict:
    if venue_status not in VENUE_STATUSES:
        raise StudyError(f"Unknown venue status {venue_status}; expected one of {VENUE_STATUSES}.")
    out.mkdir(parents=True, exist_ok=True)
    name = "results-correction" if correction else "results"
    if (out / "results.json").exists() and not correction:
        raise StudyError("This study was already evaluated once (§8.4). A corrected run needs --correction REASON.")
    if correction and not (out / "results.json").exists():
        raise StudyError("A corrected run needs the first run in the same directory.")
    if correction and (out / "results-correction.json").exists():
        raise StudyError("The one corrected run allowed by §8.4 already exists.")

    data_report, loaded = check_data(data, spot)
    if not data_report["blockingPassed"]:
        report = {"outcome": "NICHT_AUSWERTBAR", "dataChecks": data_report}
        (out / f"{name}.json").write_text(json.dumps(report, indent=2, ensure_ascii=False), encoding="utf-8")
        return report

    months = _months_in_window()
    benchmarks, binding = parse_benchmarks(benchmarks_path)
    for series_name, series in benchmarks.items():
        missing = [m for m in months if m not in series]
        if missing:
            raise StudyError(f"Benchmark {series_name} misses months {missing[:6]}...")
    rf_by_day = parse_dtb3(data / "fred" / "DTB3.csv")
    btc_monthly = spot_monthly_returns(loaded["BTCUSDT"].spot)

    variants = {variant: run_variant(variant, loaded, benchmarks, rf_by_day, btc_monthly) for variant in ("A", "B")}
    criteria = {variant: evaluate_criteria(result) for variant, result in variants.items()}
    for variant, result in variants.items():
        result["criteria"] = criteria[variant]
    outcome = classify(criteria, {v: variants[v]["total"]["netPerYear"] for v in variants},
                       {v: variants[v]["total"]["maxDrawdownDaily"] for v in variants}, venue_status)

    funding = {symbol: funding_statistics([(e.slot, e.rate) for e in data_.funding]) for symbol, data_ in loaded.items()}
    regimes = None
    if all(data_.spot_daily for data_ in loaded.values()):
        labels = regime_labels(loaded["BTCUSDT"].spot_daily, loaded["ETHUSDT"].spot_daily)
        regimes = {}
        for symbol, data_ in loaded.items():
            by_day = daily_funding([(e.slot, e.rate) for e in data_.funding])
            regimes[symbol] = {}
            for label in ("RISK_ON", "NEUTRAL", "MIXED", "RISK_OFF", "UNKNOWN"):
                values = [by_day[day] * 365 for day, value in labels.items() if value == label and day in by_day]
                regimes[symbol][label] = {"days": len(values), "meanAnnualized": statistics.fmean(values) if values else None}

    selected = outcome["selectedVariant"]
    comparison_source = selected or "A"
    report = {
        "study": STUDY_KEY,
        "scriptVersion": SCRIPT_VERSION,
        "scriptSha256": sha256_file(Path(__file__)),
        "preregistration": PREREGISTRATION,
        "synthetic": data_report["synthetic"],
        "correction": correction,
        "dataFingerprint": data_report["dataFingerprint"],
        "dataChecks": data_report,
        "window": [iso(WINDOW_START), iso(WINDOW_END)],
        "multipleTestN": MULTIPLE_TEST_N,
        **outcome,
        "variants": variants,
        "benchmarks": benchmark_summary(benchmarks, binding, months, btc_monthly),
        "portfolioComparison": portfolio_comparison(benchmarks, variants[comparison_source]["total"]["monthlyReturns"], months),
        "portfolioComparisonVariant": comparison_source,
        "funding": funding,
        "basis": {symbol: basis_statistics(data_) for symbol, data_ in loaded.items()},
        "oneLegScenario": {symbol: one_leg_scenario(data_) for symbol, data_ in loaded.items()},
        "fundingByRegime": regimes,
    }
    (out / f"{name}.json").write_text(json.dumps(report, indent=2, ensure_ascii=False), encoding="utf-8")
    (out / f"{name}.md").write_text(render_markdown(report), encoding="utf-8")
    return report


