def multiple_test_threshold(n_months: int, regressors: int = 2) -> float:
    return max(2.0, math.sqrt(2 * math.log(MULTIPLE_TEST_N)), student_t975(n_months - regressors - 1))


def evaluate_criteria(variant: dict) -> dict:
    total, alpha = variant["total"], variant["alpha"]
    b1 = total["excessAfterHaircut"] > 0
    b2 = total["excessAfterHaircutSince2024"] > 0
    b3 = total["positiveYears"] >= MIN_POSITIVE_YEARS and total["negativeMonthShare"] <= MAX_NEGATIVE_MONTH_SHARE
    b4 = total["maxDrawdownDaily"] <= MAX_DRAWDOWN and total["worstMonth"] >= MIN_WORST_MONTH and variant["liquidations"] == 0
    threshold = multiple_test_threshold(alpha["months"]) if alpha["months"] >= 6 else None
    correlation = variant["correlation"]["challengerPearson"]
    b5 = (alpha["tStat"] is not None and threshold is not None and alpha["tStat"] >= threshold
          and (variant["alphaFirstPeriod"]["alpha"] or 0) > 0 and (variant["alphaSince2024"]["alpha"] or 0) > 0
          and correlation is not None and correlation <= MAX_CHALLENGER_CORRELATION)
    b6 = (variant["costStress"]["finalEquity"] > variant["costStress"]["startEquity"]
          and variant["legging"]["finalEquity"] > variant["legging"]["startEquity"]
          and all(sleeve["finalEquity"] > sleeve["startEquity"] for sleeve in variant["sleeves"].values()))
    return {"B1": b1, "B2": b2, "B3": b3, "B4": b4, "B5": b5, "B6": b6, "alphaThreshold": threshold}


def classify(criteria: dict[str, dict], net: dict[str, float], drawdown: dict[str, float], venue_status: str) -> dict:
    """Outcome class (§8.2) and the choice between two passing variants (§8.3)."""
    keys = ("B1", "B2", "B3", "B4", "B5", "B6")
    passing = [v for v in ("A", "B") if all(criteria[v][k] for k in keys)]
    compressed = [v for v in ("A", "B") if not criteria[v]["B2"] and all(criteria[v][k] for k in keys if k != "B2")]
    selected = None
    if len(passing) == 2:
        # "at least 1.0 pp": a tiny tolerance keeps exactly 1.0 pp from failing on float rounding
        selected = "B" if net["B"] - net["A"] >= SELECTION_MARGIN - 1e-12 and drawdown["B"] <= drawdown["A"] else "A"
    elif passing:
        selected = passing[0]
    if selected is not None:
        if venue_status == "VERFUEGBAR":
            outcome = "BESTANDEN"
        elif venue_status == "OFFEN":
            outcome = "AUSSTEHEND_PHASE_1B"
        else:
            outcome = "BESTANDEN_REFERENZ"
    elif compressed:
        outcome = "KOMPRIMIERT"
    else:
        outcome = "NICHT_BESTANDEN"
    return {"outcome": outcome, "passingVariants": passing, "selectedVariant": selected, "venueStatus": venue_status}


